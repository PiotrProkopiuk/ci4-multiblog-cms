    public function __construct()
    {
        parent::__construct();

        $databaseUrl = getenv('DATABASE_URL') ?: env('DATABASE_URL');

        if ($databaseUrl) {
            $parts = parse_url($databaseUrl);

            if ($parts !== false) {
                $this->default['hostname'] = $parts['host'] ?? $this->default['hostname'];
                $this->default['username'] = isset($parts['user']) ? rawurldecode($parts['user']) : $this->default['username'];
                $this->default['password'] = isset($parts['pass']) ? rawurldecode($parts['pass']) : $this->default['password'];
                $this->default['database'] = isset($parts['path']) ? ltrim($parts['path'], '/') : $this->default['database'];
                $this->default['port'] = isset($parts['port']) ? (int) $parts['port'] : $this->default['port'];
            }
        }

        $this->default['hostname'] = getenv('PGHOST') ?: env('PGHOST') ?: $this->default['hostname'];
        $this->default['username'] = getenv('PGUSER') ?: env('PGUSER') ?: $this->default['username'];
        $this->default['password'] = getenv('PGPASSWORD') ?: env('PGPASSWORD') ?: $this->default['password'];
        $this->default['database'] = getenv('PGDATABASE') ?: env('PGDATABASE') ?: $this->default['database'];
        $this->default['port'] = (int) (getenv('PGPORT') ?: env('PGPORT') ?: $this->default['port']);

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
        }
    }
